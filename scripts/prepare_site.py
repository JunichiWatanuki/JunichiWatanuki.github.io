#!/usr/bin/env python3
"""Create a fresh staging directory without modifying source files."""
from __future__ import annotations

import argparse
import os
import shutil
from pathlib import Path

from content import KINDS

ROOT = Path(__file__).resolve().parent.parent
MARKER = ".greenlog-build"


def prepare(root: Path, site: Path):
    root, site = root.resolve(), site.resolve()
    if site == root or site in root.parents or site == Path(site.anchor):
        raise ValueError("The output directory must not be the repository or an ancestor of it")
    for protected in (root / "data", root / "scripts", root / ".github", root / ".git"):
        if site == protected or protected in site.parents:
            raise ValueError(f"Output must not be inside a protected source directory: {site}")
    source_root = root / "data" / "sources"
    if source_root.is_symlink():
        raise ValueError(f"Symlink in source tree is not allowed: {source_root}")
    if source_root.is_dir():
        for source in source_root.rglob("*"):
            if source.is_symlink():
                raise ValueError(f"Symlink in source tree is not allowed: {source}")
    if site.exists():
        if not site.is_dir():
            raise ValueError(f"Output is not a directory: {site}")
        if any(site.iterdir()) and not (site / MARKER).is_file():
            raise ValueError(f"Refusing to delete a nonempty directory without {MARKER}: {site}")
        shutil.rmtree(site)
    site.mkdir(parents=True)
    (site / MARKER).write_text("Generated by greenlog; safe to rebuild.\n", encoding="utf-8")
    if not (root / "index.html").is_file():
        raise ValueError(f"Missing site root index.html: {root / 'index.html'}")

    # Copy the published site and external media, not source code or old builds.
    skip_root = {".git", ".github", "scripts", "TODO.md", ".venv", ".site", "_site", "node_modules", "__pycache__"}
    for current, dirs, files in os.walk(root):
        here = Path(current)
        rel = here.relative_to(root)
        dirs[:] = [name for name in dirs
                   if not (rel == Path(".") and name in skip_root)
                   and (here / name).resolve() != site
                   and (here / name) not in (root / "data" / "sources", root / "data" / "contents")
                   and name != "__pycache__"]
        for name in files:
            src = here / name
            if rel == Path(".") and name in skip_root:
                continue
            dest = site / rel / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest)

    # Preserve media throughout the source tree in a parallel contents tree. Also
    # publish it under sources/ so explicit references to that location survive.
    source_root = root / "data" / "sources"
    if source_root.is_dir():
        for src in sorted(source_root.rglob("*")):
            if not src.is_file():
                continue
            rel = src.relative_to(source_root)
            kind = rel.parts[0] if rel.parts else ""
            if kind in KINDS:
                if ((len(rel.parts) == 2 and rel.name == "index.html") or
                        src.suffix.lower() == KINDS[kind] or
                        (kind == "training" and src.suffix.lower() == ".csv")):
                    continue
            for base in (site / "data" / "sources", site / "data" / "contents"):
                # Kind assets are recreated by each independent kind action.
                if base.name == "contents" and kind in KINDS:
                    continue
                dest = base / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dest)
    print(f"Prepared clean site at {site}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site-dir", type=Path, required=True, help="Build directory; previous generated content is replaced")
    args = parser.parse_args()
    prepare(ROOT, args.site_dir)


if __name__ == "__main__":
    main()
